export function translateCrop(cropName: string | null | undefined, lang: Language): string {
  if (!cropName) return "";
  const key = cropName.trim().toLowerCase();
  if (CROP_TRANSLATIONS[key]) {
    return CROP_TRANSLATIONS[key][lang] || cropName;
  }
  return cropName;
}

export function translateUnit(unit: string | null | undefined, lang: Language): string {
  if (!unit) return "";
  const u = unit.trim().toLowerCase();
  if (u === "maund" || u === "mann" || u === "mnds") return lang === "sd" ? "مڻ" : lang === "ur" ? "من" : "Maund";
  if (u === "kg") return lang === "sd" ? "ڪلو" : lang === "ur" ? "کلو" : "Kg";
  if (u === "ton" || u === "tons") return lang === "sd" ? "ٽن" : lang === "ur" ? "ٹن" : "Ton";
  if (u === "acre" || u === "acres") return lang === "sd" ? "ايڪڙ" : lang === "ur" ? "ایکڑ" : "Acre";
  if (u === "hectare" || u === "hectares") return lang === "sd" ? "هيڪٽر" : lang === "ur" ? "ہیکٹر" : "Hectare";
  if (u === "bag" || u === "bags") return lang === "sd" ? "بوريون" : lang === "ur" ? "بوریاں" : "Bags";
  return unit;
}

